#!/usr/bin/env python3
"""Generate the per-function bindings from the FractalFn registry.

The registry in FractalFn.java is the source of truth for the function
names and shapes. Druid's Guice bindings take a *class*, so each function
needs its own macro and operator-conversion class; those are generated
from the same table rather than hand-written, so the registry and the
bindings cannot drift.

Run:
    python druid-extension/tools/generate-fn-bindings.py
"""

import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
JAVA = HERE.parent / "src/main/java/com/fractalsqlabs/fractalsql/druid"
FN = JAVA / "FractalFn.java"
OUT_PKG = "com.fractalsqlabs.fractalsql.druid.fn"

text = FN.read_text(encoding="utf-8")

entries = re.findall(
    # A Java array is written either "new ArgType[] {a, b}" or, when it
    # is empty, "new ArgType[0]" -- both forms are in the registry.
    r'add\((\d+),\s*"(FRACTAL\w*)",\s*RetType\.(\w+),\s*'
    r'new\s+ArgType\s*\[(?:\s*0\s*\]|\s*\]\s*\{\s*([^}]*?)\s*\})\s*,\s*'
    r'new\s+int\s*\[(?:\s*0\s*\]|\s*\]\s*\{\s*([^}]*?)\s*\})'
    r'([^)]*)\);',
    text,
    re.S,
)
if not entries:
    raise SystemExit("no registry entries found in FractalFn.java")


def camel(sql_name: str) -> str:
    """FractalDimensionDfa, FractalSqlVersion, ...

    Both the FRACTAL_ and the FRACTALSQL_ prefixes are stripped, so the
    generated class names stay readable whichever prefix the function
    carries.
    """
    body = sql_name
    if body.startswith("FRACTAL_"):
        body = body[len("FRACTAL_"):]
    elif body.startswith("FRACTAL"):
        body = body[len("FRACTAL"):]
    return "Fractal" + "".join(
        p[:1].upper() + p[1:] for p in body.lower().split("_") if p
    )


pkg_dir = JAVA / "fn"
pkg_dir.mkdir(parents=True, exist_ok=True)
for stale in pkg_dir.glob("*.java"):
    stale.unlink()

# The reasoning functions need the reasoning bridge, so their macros are
# hand-written in the base package rather than generated here. Their SQL
# bindings are still generated.
HAND_WRITTEN_MACROS = {
    "FRACTAL_REASON",
    "FRACTAL_EMBED",
}

names = []
for fn_id, sql_name, ret, types, slots, extra in entries:
    base = camel(sql_name)
    names.append((base, sql_name))

    macro = f"""/*
 * SPDX-License-Identifier: Apache-2.0
 * Copyright 2026 Daniel Gardiner d/b/a FractalSQLabs
 */
package {OUT_PKG};

import com.fractalsqlabs.fractalsql.druid.FractalExprMacro;
import com.fractalsqlabs.fractalsql.druid.FractalFn;

/**
 * The native expression macro for {sql_name}.
 *
 * <p>Generated by tools/generate-fn-bindings.py from the registry in
 * FractalFn.java -- the registry is the source of truth for the
 * function's name and argument shape.
 */
public class {base}ExprMacro extends FractalExprMacro
{{
    @Override
    protected FractalFn.Spec spec()
    {{
        return FractalFn.byName("{sql_name}");
    }}
}}
"""

    conversion = f"""/*
 * SPDX-License-Identifier: Apache-2.0
 * Copyright 2026 Daniel Gardiner d/b/a FractalSQLabs
 */
package {OUT_PKG};

import com.fractalsqlabs.fractalsql.druid.FractalFn;
import com.fractalsqlabs.fractalsql.druid.FractalOperatorConversion;

/**
 * The SQL binding for {sql_name}.
 *
 * <p>Generated by tools/generate-fn-bindings.py from the registry in
 * FractalFn.java -- the registry is the source of truth for the
 * function's name and argument shape.
 */
public class {base}OperatorConversion extends FractalOperatorConversion
{{
    @Override
    protected FractalFn.Spec spec()
    {{
        return FractalFn.byName("{sql_name}");
    }}
}}
"""
    if sql_name not in HAND_WRITTEN_MACROS:
        (pkg_dir / f"{base}ExprMacro.java").write_text(macro, encoding="utf-8")
    (pkg_dir / f"{base}OperatorConversion.java").write_text(conversion, encoding="utf-8")

def class_list(suffix: str, only_generated: bool = False) -> str:
    """A List.of(...) body -- no trailing comma, which Java rejects."""
    entries = [
        (b, s) for (b, s) in names
        if not (only_generated and s in HAND_WRITTEN_MACROS)
    ]
    return ",\n".join("            " + b + suffix for b, _ in entries)


bindings = f"""/*
 * SPDX-License-Identifier: Apache-2.0
 * Copyright 2026 Daniel Gardiner d/b/a FractalSQLabs
 */
package {OUT_PKG};

import org.apache.druid.math.expr.ExprMacroTable;
import org.apache.druid.sql.calcite.expression.SqlOperatorConversion;

import java.util.List;

/**
 * Every ported function's macro and SQL binding.
 *
 * <p>Generated by tools/generate-fn-bindings.py from the registry in
 * FractalFn.java -- Druid's Guice bindings take a class, so each
 * function needs its own.
 */
public final class FractalFnBindings
{{
    public static final List<Class<? extends ExprMacroTable.ExprMacro>> MACROS = List.of(
{class_list('ExprMacro.class', only_generated=True)}
    );

    public static final List<Class<? extends SqlOperatorConversion>> CONVERSIONS = List.of(
{class_list('OperatorConversion.class')}
    );

    private FractalFnBindings()
    {{
    }}
}}
"""
(pkg_dir / "FractalFnBindings.java").write_text(bindings, encoding="utf-8")

print(f"generated {len(names)} functions in {pkg_dir}")
for b, s in names:
    print(f"  {s}")
